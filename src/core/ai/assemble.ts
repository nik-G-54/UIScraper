export interface RulesParts {
  /** Title line(s) before `## 0`. */
  head: string;
  /** `## 0. Build checklist` block. */
  checklist: string;
  /** `## 1. Instructions for the AI agent` block. */
  instructions: string;
  /** Everything from `## 2. Overview` on. */
  reference: string;
}

/** Split the rule-based design.md at its fixed headings; null when it does not have the expected shape. */
export function splitRulesMd(md: string): RulesParts | null {
  const i0 = md.indexOf('## 0. Build checklist');
  const i1 = md.indexOf('\n## 1. Instructions');
  const i2 = md.indexOf('\n## 2. Overview');
  if (i0 < 0 || i1 < i0 || i2 < i1) return null;
  return { head: md.slice(0, i0).trimEnd(), checklist: md.slice(i0, i1).trim(), instructions: md.slice(i1 + 1, i2).trim(), reference: md.slice(i2 + 1).trim() };
}

export const REFERENCE_HEADING = '# Reference data (exact, generated by rules)';

/**
 * Final design.md when the AI layer ran: build checklist + agent instructions + AI output + the
 * rule-based sections 2-8 unchanged under the reference-data heading. Falls back to the rule-based
 * text when it cannot be split.
 */
export function assembleFinalDesignMd(rulesMd: string, aiText: string, model: string): string {
  const parts = splitRulesMd(rulesMd);
  if (!parts) return rulesMd;
  return [
    parts.head,
    '',
    parts.checklist,
    '',
    parts.instructions,
    '',
    `> The sections below (Summary to Gaps) were written by AI (${model}) from the screenshots and the data. They describe; they do not define values. The exact values are in "Reference data" and win over anything written here.`,
    '',
    aiText.trim(),
    '',
    REFERENCE_HEADING,
    '',
    parts.reference,
    '',
  ].join('\n');
}
