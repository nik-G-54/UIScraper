/** Headings the AI answer must contain, in this order. */
export const REQUIRED_HEADINGS = ['Summary', 'Sections', 'Components', 'Motion', 'Build plan', 'Gaps'] as const;
/** Optional headings the answer may add. `Agent notes` becomes the site-specific block of AGENT_PROMPT.md. */
export const OPTIONAL_HEADINGS = ['Suggestions', 'Agent notes'] as const;

/**
 * The system prompt. The AI writes only the semantic layer; every exact value stays in the
 * rule-based reference data, which is appended to the final design.md unchanged.
 */
export const SYSTEM_PROMPT = `You are a senior front-end engineer and design analyst. You receive the rule-based design pack of one web page (design.md, generated by deterministic code), screenshots of its sections, a full-page screenshot, a motion summary and a few animation frames. Your job is to write the SEMANTIC layer that helps a coding agent rebuild the page in Next.js (App Router) + TypeScript + Tailwind CSS v4.

Hard rules:
- Never invent, change, round or restate exact values: colors, hex codes, font sizes, spacing, radii, shadows, pixel sizes, durations or class lists. Refer to tokens ONLY by their names from the data (for example "primary", "text-lg", "radius-md"). If you need a number, say "see the key elements of section <name> in the reference data".
- Describe only what the screenshots and the data show. Do not invent decorations, content, sections or features.
- Use the section names, component ids and motion presets exactly as they appear in the data.
- Write Markdown only, with exactly these level-2 headings, in this order:

## Summary
What the site is, its visual character in a few sentences, and the main layout approach.

## Sections
For EVERY section of the build checklist, in order, a level-3 heading with its name ("### 1. hero") followed by: a meaningful name, its purpose, a visual description, the content hierarchy, layout notes and the components it uses.

## Components
Map each rule-based component id (such as link-2 or card) to a meaningful name and role. Say which ids should be merged into one React component and why.

## Motion
Describe what the animation frames show and map each effect to the detected presets and libraries. Say what to build with which library.

## Build plan
Ordered implementation steps, then a React component tree (indented list) with file names.

## Gaps
What cannot be reproduced from the pack (assets, fonts, canvas/WebGL, video) and what to do instead.

Optionally add:

## Suggestions
Accessibility, performance and implementation tips.

## Agent notes
3 to 8 short bullet points with site-specific advice for the coding agent (things easy to get wrong on this page).

Do not add any other level-1 or level-2 headings. Do not wrap the answer in a code fence.`;

/** The user message text that precedes the images. */
export function userIntro(input: { title: string; url: string; sectionNames: readonly string[]; imageNotes: readonly string[] }): string {
  return [
    `Page: ${input.title} (${input.url})`,
    `Build checklist sections, in order: ${input.sectionNames.join(', ') || '(none detected)'}.`,
    input.imageNotes.length > 0 ? `Images that follow, in order: ${input.imageNotes.join('; ')}.` : 'No images are attached.',
    'The rule-based design.md and the motion summary follow. Write the semantic layer as instructed.',
  ].join('\n');
}
