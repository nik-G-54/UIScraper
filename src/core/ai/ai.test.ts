const GOOD = `## Summary\nA landing page.\n\n## Sections\n### 1. hero\nBig heading.\n\n## Components\nbutton is the CTA.\n\n## Motion\nFade-up reveals.\n\n## Build plan\n1. Setup\n\n## Gaps\nNo video.\n\n## Agent notes\n- Keep the hero tight.\n`;
const response = (text = GOOD, finishReason = 'STOP'): GenerateResponse => ({ text, finishReason, usage: { inputTokens: 1000, outputTokens: 500, totalTokens: 1500 } });

describe('decideAi', () => {
  it('skips for Off, a missing key and a reached limit, and says why', () => {
    expect(decideAi({ mode: 'off', apiKey: 'k', used: 0, limit: 15 })).toEqual({ run: false, reason: 'AI mode is Off' });
    expect(decideAi({ mode: 'auto', apiKey: '  ', used: 0, limit: 15 })).toMatchObject({ run: false, reason: expect.stringContaining('API key') });
    expect(decideAi({ mode: 'always', apiKey: 'k', used: 15, limit: 15 })).toMatchObject({ run: false, reason: expect.stringContaining('15/15') });
    expect(decideAi({ mode: 'auto', apiKey: 'k', used: 14, limit: 15 })).toEqual({ run: true });
    expect(decideAi({ mode: 'auto', apiKey: 'k', used: 0, limit: 0 }).run).toBe(false);
  });
});

describe('maskPersonalData', () => {
  it('masks emails and phone numbers but leaves sizes and coordinates alone', () => {
    const text = 'Mail sales@acme.io or call +1 (555) 123-4567, 555-123-4567 or +44 20 7946 0958. Rect 0 0 1440 1000, x 190, y 2048, 1px #e5edf5.';
    const masked = maskPersonalData(text);
    expect(masked).not.toContain('sales@acme.io');
    expect(masked).not.toMatch(/555-123-4567|7946/);
    expect(masked).toContain('[email]');
    expect(masked.match(/\[phone\]/g)).toHaveLength(3);
    expect(masked).toContain('0 0 1440 1000, x 190, y 2048, 1px #e5edf5');
  });
});

describe('validateAiOutput', () => {
  it('accepts a complete answer (also inside a fence) and extracts sections', () => {
    expect(validateAiOutput(GOOD, 'STOP')).toMatchObject({ ok: true });
    expect(validateAiOutput(`\`\`\`markdown\n${GOOD.trim()}\n\`\`\``, 'STOP')).toMatchObject({ ok: true });
    expect(extractSection(GOOD, 'Agent notes')).toBe('- Keep the hero tight.');
  });

  it('rejects cut-off, blocked, empty and incomplete answers', () => {
    expect(validateAiOutput(GOOD, 'MAX_TOKENS')).toMatchObject({ ok: false, reason: expect.stringContaining('token limit') });
    expect(validateAiOutput(GOOD, 'SAFETY')).toMatchObject({ ok: false });
    expect(validateAiOutput('   ', 'STOP')).toMatchObject({ ok: false });
    expect(validateAiOutput(GOOD.replace('## Motion\nFade-up reveals.\n', ''), 'STOP')).toMatchObject({ ok: false, reason: expect.stringContaining('## Motion') });
    expect(validateAiOutput(GOOD.replace('No video.', ''), 'STOP')).toMatchObject({ ok: false, reason: expect.stringContaining('## Gaps') });
  });
});

describe('assembleFinalDesignMd', () => {
  const rules = '# Design pack: Acme\n\n## 0. Build checklist\n\n1. [ ] hero — screenshot: x\n\n## 1. Instructions for the AI agent\n\n- be exact\n\n## 2. Overview\n\n- URL: https://acme.test\n\n## 3. Design tokens\n\n| a | b |\n';

  it('puts checklist, instructions, AI text, then the rule-based reference data unchanged', () => {
    const parts = splitRulesMd(rules);
    expect(parts?.reference.startsWith('## 2. Overview')).toBe(true);
    const md = assembleFinalDesignMd(rules, GOOD, 'gemini-3.8-flash');
    const order = ['## 0. Build checklist', '## 1. Instructions', '## Summary', '## Sections', '## Gaps', '# Reference data (exact, generated by rules)', '## 2. Overview', '## 3. Design tokens'].map((h) => md.indexOf(h));
    expect(order.every((i) => i >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
    expect(md).toContain('written by AI (gemini-3.8-flash)');
    expect(md).toContain('- URL: https://acme.test\n\n## 3. Design tokens\n\n| a | b |');
  });

  it('keeps the rule-based text when it has an unexpected shape', () => {
    expect(assembleFinalDesignMd('# Just a title', GOOD, 'm')).toBe('# Just a title');
  });
});

const inputs = (over: Partial<AiInputs> = {}): AiInputs => ({
  title: 'Acme',
  url: 'https://acme.test',
  sectionNames: ['hero'],
  designMd: '# Design pack\n\n## 2. Overview\n\nx\n\n## 3. Design tokens\n\ny\n\n## 4. Layout\n\nlayout\n\n## 6. Assets index\n\nassets\n\n## 7. Responsive\n\nr\n',
  motionSummary: 'Libraries: none',
  sectionShots: [{ label: 'section hero', base64: 'AAAA', bytes: 3 }],
  fullPage: { label: 'full page', base64: 'BBBB', bytes: 3 },
  heroFrames: [{ label: 'frame 1', base64: 'CCCC', bytes: 3 }],
  ...over,
});

describe('fitInput', () => {
  const imageCount = (parts: { kind: string }[]) => parts.filter((p) => p.kind === 'image').length;

  it('drops frames, then section screenshots, then shortens text, and reports what it dropped', async () => {
    const sizes = [1_000, 700, 400, 300, 100];
    let calls = 0;
    const fit = await fitInput(inputs(), false, async () => sizes[calls++] as number, 450);
    expect(fit.parts).not.toBeNull();
    expect(fit.dropped).toEqual(['motion frames', 'section screenshots']);
    expect(imageCount(fit.parts ?? [])).toBe(1); // the full-page image stays

    calls = 0;
    const tight = await fitInput(inputs(), false, async () => sizes[calls++] as number, 150);
    expect(tight.dropped).toEqual(['motion frames', 'section screenshots', 'asset and responsive details', 'overview and token details']);
    expect(JSON.stringify(tight.parts)).not.toContain('assets');
  });

  it('gives up with a reason when nothing fits', async () => {
    const fit = await fitInput(inputs(), false, async () => 999_999, 1_000);
    expect(fit.parts).toBeNull();
    expect('reason' in fit && fit.reason).toContain('over the 1,000 budget');
  });

  it('masks personal data in the text it sends', async () => {
    const fit = await fitInput(inputs({ designMd: 'Contact me@x.io' }), true, async () => 1, 10);
    expect(JSON.stringify(fit.parts)).toContain('[email]');
    expect(JSON.stringify(fit.parts)).not.toContain('me@x.io');
  });
});

function setup(generate: AiProvider['generate'], over: Partial<RunAiOptions> = {}) {
  let used = 0;
  const provider: AiProvider = { id: 'mock', generate: vi.fn(generate), countTokens: vi.fn(async () => 5_000), testKey: vi.fn() };
  const sleep = vi.fn(async () => undefined);
  const recordRequest = vi.fn(async () => ++used);
  const options: RunAiOptions = {
    provider,
    mode: 'auto',
    apiKey: 'key',
    model: 'main',
    fallbackModel: 'fallback',
    dailyLimit: 15,
    getUsed: async () => used,
    recordRequest,
    inputs: inputs(),
    mask: true,
    inputTokenBudget: 100_000,
    maxOutputTokens: 1000,
    maxRetries: 2,
    backoffMs: [100, 200],
    sleep,
    ...over,
  };
  return { options, provider, sleep, recordRequest };
}

const models = (provider: AiProvider) => (provider.generate as ReturnType<typeof vi.fn>).mock.calls.map((c) => (c[0] as { model: string }).model);

describe('runAi', () => {
  it('enhances with the main model and counts the request and tokens', async () => {
    const { options, provider, recordRequest } = setup(async () => response());
    const outcome = await runAi(options);
    expect(outcome).toMatchObject({ enhanced: true, model: 'main', requests: 1, usedToday: 1, tokens: { input: 1000, output: 500 }, siteNotes: '- Keep the hero tight.' });
    expect(models(provider)).toEqual(['main']);
    expect(recordRequest).toHaveBeenCalledTimes(1);
  });

  it('retries 429/5xx with backoff on the main model, counting every request', async () => {
    let n = 0;
    const { options, provider, sleep } = setup(async () => {
      if (++n < 3) throw new AiError(n === 1 ? 'rate-limit' : 'server', 'busy', n === 1 ? 429 : 503);
      return response();
    });
    const outcome = await runAi(options);
    expect(outcome).toMatchObject({ enhanced: true, model: 'main', requests: 3, usedToday: 3 });
    expect(models(provider)).toEqual(['main', 'main', 'main']);
    expect((sleep.mock.calls as unknown as number[][]).map((c) => c[0])).toEqual([100, 200]);
  });

  it('switches to the fallback model once after the retries are used up', async () => {
    const { options, provider } = setup(async (req) => {
      if (req.model === 'main') throw new AiError('rate-limit', 'quota', 429);
      return response();
    });
    const outcome = await runAi(options);
    expect(outcome).toMatchObject({ enhanced: true, model: 'fallback', requests: 4 });
    expect(models(provider)).toEqual(['main', 'main', 'main', 'fallback']);
  });

  it('falls back to rule-based when both models fail, with both reasons', async () => {
    const { options } = setup(async () => {
      throw new AiError('server', 'down', 500);
    });
    const outcome = await runAi(options);
    expect(outcome).toMatchObject({ enhanced: false, text: null, model: null, requests: 4 });
    expect(outcome.reason).toContain('main: down');
    expect(outcome.reason).toContain('fallback: down');
  });

  it('retries once on the fallback model when the main answer is invalid, then gives up', async () => {
    const bad = response('## Summary\nonly this', 'STOP');
    const a = setup(async (req) => (req.model === 'main' ? bad : response()));
    expect(await runAi(a.options)).toMatchObject({ enhanced: true, model: 'fallback', requests: 2 });
    const b = setup(async () => response(GOOD, 'MAX_TOKENS'));
    const outcome = await runAi(b.options);
    expect(outcome).toMatchObject({ enhanced: false, requests: 2 });
    expect(outcome.reason).toContain('main: the answer was cut off');
    expect(models(b.provider)).toEqual(['main', 'fallback']);
  });

  it('does not retry or switch model for a rejected key or a bad request', async () => {
    const auth = setup(async () => {
      throw new AiError('auth', 'The API key was rejected', 403);
    });
    expect(await runAi(auth.options)).toMatchObject({ enhanced: false, requests: 1, reason: 'The API key was rejected' });
    const bad = setup(async () => {
      throw new AiError('bad-request', 'too large', 400);
    });
    const outcome = await runAi(bad.options);
    expect(outcome).toMatchObject({ enhanced: false, requests: 1 });
    expect(models(bad.provider)).toEqual(['main']);
  });

  it('sends nothing when the pre-check says no, or the input cannot fit', async () => {
    const off = setup(async () => response(), { mode: 'off' });
    expect(await runAi(off.options)).toMatchObject({ enhanced: false, requests: 0, reason: 'AI mode is Off' });
    expect(off.provider.generate).not.toHaveBeenCalled();

    const limit = setup(async () => response(), { dailyLimit: 0 });
    expect((await runAi(limit.options)).reason).toContain('daily AI limit');

    const huge = setup(async () => response(), { inputTokenBudget: 10 });
    const outcome = await runAi(huge.options);
    expect(outcome).toMatchObject({ enhanced: false, requests: 0, dropped: expect.arrayContaining(['motion frames', 'section screenshots']) });
    expect(outcome.reason).toContain('over the 10 budget');
  });

  it('stops retrying when the daily limit is reached mid-chain', async () => {
    const { options } = setup(
      async () => {
        throw new AiError('rate-limit', 'quota', 429);
      },
      { dailyLimit: 2 },
    );
    const outcome = await runAi(options);
    expect(outcome.requests).toBe(2);
    expect(outcome.reason).toContain('daily AI limit');
  });

  it('estimates tokens when counting fails, but stops on a rejected key', async () => {
    const { options, provider } = setup(async () => response());
    (provider.countTokens as ReturnType<typeof vi.fn>).mockRejectedValue(new AiError('network', 'offline'));
    expect(await runAi(options)).toMatchObject({ enhanced: true });
    (provider.countTokens as ReturnType<typeof vi.fn>).mockRejectedValue(new AiError('auth', 'bad key', 403));
    expect(await runAi(options)).toMatchObject({ enhanced: false, reason: 'bad key' });
  });
});

describe('createGeminiProvider', () => {
  const reply = (status: number, body: unknown) => vi.fn(async () => new Response(JSON.stringify(body), { status }));

  it('sends the key in x-goog-api-key and parses text, finish reason and usage', async () => {
    const fetchMock = reply(200, {
      candidates: [{ content: { parts: [{ text: 'Hello ' }, { text: 'world' }] }, finishReason: 'STOP' }],
      usageMetadata: { promptTokenCount: 10, candidatesTokenCount: 4, totalTokenCount: 14 },
    });
    const provider = createGeminiProvider({ apiKey: 'SECRET', fetch: fetchMock as unknown as typeof fetch });
    const out = await provider.generate({ model: 'm', system: 's', parts: [{ kind: 'text', text: 'hi' }, { kind: 'image', mimeType: 'image/jpeg', base64: 'AAA' }] });
    expect(out).toEqual({ text: 'Hello world', finishReason: 'STOP', usage: { inputTokens: 10, outputTokens: 4, totalTokens: 14 } });
    const [url, init] = fetchMock.mock.calls[0] as unknown as [string, RequestInit];
    expect(url).toBe('https://generativelanguage.googleapis.com/v1beta/models/m:generateContent');
    expect((init.headers as Record<string, string>)['x-goog-api-key']).toBe('SECRET');
    expect(url).not.toContain('SECRET');
    const body = JSON.parse(init.body as string);
    expect(body.systemInstruction.parts[0].text).toBe('s');
    expect(body.contents[0].parts[1]).toEqual({ inlineData: { mimeType: 'image/jpeg', data: 'AAA' } });
  });

  it('classifies errors without leaking the key', async () => {
    const call = (status: number, message: string) =>
      createGeminiProvider({ apiKey: 'SECRET', fetch: reply(status, { error: { message } }) as unknown as typeof fetch }).generate({ model: 'm', system: '', parts: [] });
    await expect(call(429, 'quota')).rejects.toMatchObject({ kind: 'rate-limit', retryable: true });
    await expect(call(503, 'overloaded')).rejects.toMatchObject({ kind: 'server', retryable: true });
    await expect(call(400, 'API key not valid')).rejects.toMatchObject({ kind: 'auth', retryable: false });
    await expect(call(400, 'bad part')).rejects.toMatchObject({ kind: 'bad-request', retryable: false });
    const failing = createGeminiProvider({ apiKey: 'SECRET', fetch: vi.fn(async () => { throw new Error('offline'); }) as unknown as typeof fetch });
    await expect(failing.generate({ model: 'm', system: '', parts: [] })).rejects.toMatchObject({ kind: 'network' });
  });

  it('tests the key with the models endpoint: ok, invalid key, network error', async () => {
    const ok = createGeminiProvider({ apiKey: 'k', fetch: reply(200, { models: [] }) as unknown as typeof fetch });
    expect(await ok.testKey()).toEqual({ ok: true });
    const bad = createGeminiProvider({ apiKey: 'k', fetch: reply(403, { error: { message: 'denied' } }) as unknown as typeof fetch });
    expect(await bad.testKey()).toMatchObject({ ok: false, kind: 'invalid-key' });
    const down = createGeminiProvider({ apiKey: 'k', fetch: vi.fn(async () => { throw new Error('offline'); }) as unknown as typeof fetch });
    expect(await down.testKey()).toMatchObject({ ok: false, kind: 'network' });
    expect((ok as { id: string }).id).toBe('gemini');
  });
});
