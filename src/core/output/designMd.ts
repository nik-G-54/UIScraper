const cell = (value: string | number | null | undefined): string => String(value ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ');
const code = (value: string): string => `\`${value.replace(/`/g, "'")}\``;
const clip = (value: string, max: number): string => (value.length > max ? `${value.slice(0, max - 1)}…` : value);
const px = (n: number): string => `${Math.round(n * 100) / 100}px`;
const more = (shown: number, total: number, what: string): string[] =>
  total > shown ? [`- … and ${total - shown} more ${what} (see tokens.json / capture.json)`] : [];

function table(header: string[], rows: (string | number | null)[][]): string[] {
  if (rows.length === 0) return [];
  return [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)];
}

