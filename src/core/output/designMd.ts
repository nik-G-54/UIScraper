function overview(input: DesignMdInput, caps: Caps): string[] {
  const { meta, stats } = input.capture;
  const frameworks = input.tokens.frameworks.map((f) => (f.version ? `${f.name} ${f.version}` : f.name));
  const scheme = [meta.colorSchemeMeta ? `meta color-scheme: ${meta.colorSchemeMeta}` : null, input.tokens.darkMode ? 'has a dark theme' : 'light only'].filter(Boolean);
  const lines = [
    '## 2. Overview',
    '',
    `- **URL:** ${meta.url}`,
    `- **Title:** ${meta.title || '(none)'}`,
    `- **Captured:** ${meta.timestamp}`,
    `- **Capture width:** ${meta.captureWidth}px (${meta.emulated ? 'forced with viewport emulation' : 'current window width'}), page ${Math.round(meta.documentWidth)}×${Math.round(meta.documentHeight)}px`,
    `- **Language / direction:** ${meta.lang || 'unknown'} / ${meta.dir}`,
    `- **Frameworks detected:** ${frameworks.length > 0 ? frameworks.join(', ') : 'none'}`,
    `- **Color scheme:** ${scheme.join('; ')}`,
    `- **Captured nodes:** ${stats.nodesCaptured}${stats.truncated ? ` (truncated by: ${stats.truncatedReasons.join(', ')})` : ''}`,
  ];
  if (input.warnings.length > 0) {
    lines.push('', `**Warnings (${input.warnings.length}):**`);
    for (const w of input.warnings.slice(0, caps.warnings)) lines.push(`- ${clip(w.message, 240)}`);
    lines.push(...more(Math.min(caps.warnings, input.warnings.length), input.warnings.length, 'warnings'));
  }
  return [...lines, ''];
}

function tokenSection(input: DesignMdInput, caps: Caps): string[] {
  const { tokens } = input;
  const names = colorNames(tokens.colors);
  const lines = ['## 3. Design tokens', '', '### Colors', ''];
  lines.push(
    ...table(
      ['Token', 'Hex', 'Role', 'Used as', 'CSS variable'],
      tokens.colors.slice(0, caps.colors).map((c, i) => [
        code(names[i] ?? ''),
        code(c.hex),
        c.role,
        (['text', 'background', 'border', 'shadow', 'gradient'] as const)
          .filter((k) => c.uses[k] > 0)
          .map((k) => `${k} ${c.uses[k]}`)
          .join(', '),
        c.variable ? code(c.variable) : '',
      ]),
    ),
    ...more(Math.min(caps.colors, tokens.colors.length), tokens.colors.length, 'colors'),
    '',
    '### Gradients',
    '',
  );
  if (tokens.gradients.length === 0) lines.push('None detected.');
  for (const g of tokens.gradients.slice(0, caps.gradients)) {
    lines.push(`- ${g.repeating ? 'repeating ' : ''}${g.kind}, used ${g.count}×, stops: ${g.stops.map((s) => `${s.color}${s.position ? ` ${s.position}` : ''}`).join(' → ')}`);
    lines.push(`  ${code(clip(g.value, 220))}`);
  }
  lines.push(...more(Math.min(caps.gradients, tokens.gradients.length), tokens.gradients.length, 'gradients'));

  const t = tokens.typography;
  lines.push('', '### Typography', '');
  for (const f of t.families) {
    lines.push(`- **${f.name}** (${f.category}${f.role ? `, ${f.role}` : ''}, ${f.count} uses): ${code(f.stack)}`);
  }
  const scale = typeScaleNames(t.sizes, baseFontSize(tokens));
  if (scale.length > 0) lines.push('', `Type scale: ${scale.map((s) => `${s.name} ${s.px}px`).join(', ')}.`);
  if (t.weights.length > 0) lines.push(`Weights in use: ${t.weights.map((w) => `${w.value} (${w.count})`).join(', ')}.`);
  lines.push(
    '',
    ...table(
      ['Tag', 'Font', 'Size', 'Weight', 'Line height', 'Letter spacing', 'Color'],
      t.tags.slice(0, caps.tagStyles).map((s) => [code(s.tag), s.fontFamily, `${s.fontSizePx}px`, s.fontWeight, s.lineHeight, s.letterSpacing, s.color ? code(s.color) : '']),
    ),
  );

  const sp = tokens.spacing;
  lines.push(
    '',
    '### Spacing, radius, shadows',
    '',
    `- **Spacing:** ${sp.baseUnit ? `${sp.baseUnit}px base unit (${Math.round(sp.coverage * 100)}% of values fit)` : 'no consistent base unit'}; scale: ${sp.scale.map((s) => `${s.px}px`).join(', ') || 'n/a'}.`,
    `- **Radius:** ${tokens.radius.map((r) => `${radiusLabel(r)} (${r.count})`).join(', ') || 'none'}. Exact radii per element are in the key elements of section 4 and in section 5.`,
  );
  if (tokens.shadows.length === 0) lines.push('- **Shadows:** none.');
  else {
    lines.push('- **Shadows:**');
    for (const s of tokens.shadows) lines.push(`  - ${code(clip(s.value, 200))} (${s.count}×)`);
  }
  lines.push('', '### Theme (`theme.css`)', '', '```css', input.themeCss.trimEnd(), '```', '');
  return lines;
}

/** Percent radii only make circles/ellipses; say so instead of letting them look like a scale step. */
function radiusLabel(r: DesignTokens['radius'][number]): string {
  if (r.px === 9999) return '9999px (pill ends: only on elements whose height is at most twice the radius)';
  if (r.px === null) return `${r.value} (${r.value === '50%' || r.value === '100%' ? 'avatars/circles only' : 'percentage radius'})`;
  return r.value;
}

function describeLayout(section: PageSection): string {
  const l = section.layout;
  const parts = [l.display + (l.flexDirection ? ` ${l.flexDirection}` : ''), `${l.columns} column${l.columns === 1 ? '' : 's'}`];
  if (l.gap) parts.push(`gap ${l.gap}`);
  parts.push(l.containerMaxWidth ? `content max-width ${px(l.containerMaxWidth)}, ${l.alignment}` : `content ${l.alignment} width`);
  if (l.paddingY) parts.push(`vertical padding ${l.paddingY}`);
  return parts.join('; ');
}

const hexRef = (c: { hex: string; token: string | null } | null): string => (c ? `${c.token ? `${c.token} ` : ''}${c.hex}` : 'none');
const radiusText = (value: string | null, pill: boolean): string => (value === null ? 'square' : pill ? `${value} (pill)` : value);

function describeLines(lines: readonly DecorativeLine[]): string[] {
  const groups = new Map<string, DecorativeLine[]>();
  for (const l of lines) {
    const key = `${l.orientation}|${l.thicknessPx}|${l.color ?? ''}`;
    groups.set(key, [...(groups.get(key) ?? []), l]);
  }
  return [...groups.values()].map((group) => {
    const first = group[0] as DecorativeLine;
    const axis = first.orientation === 'vertical' ? 'x' : 'y';
    const at = group.slice(0, 6).map((l) => `${axis}=${l.at}`).join(' and ');
    const length = Math.max(...group.map((l) => l.length));
    return `${first.orientation} ${first.thicknessPx}px line${group.length === 1 ? '' : 's'} at ${at}${group.length > 6 ? ` (+${group.length - 6} more)` : ''}, color ${first.color ?? 'default'}, up to ${length}px long`;
  });
}

function keyElementLines(e: KeyElement, caps: Caps, hideNotes: ReadonlySet<string>): string[] {
  const isImage = e.role === 'image' || e.role === 'logo';
  const head = `- **${e.role}** ${code(`<${e.tag}>`)}${e.text ? ` “${clip(e.text, KEY_ELEMENTS.maxTextChars)}”` : ''} at x ${e.rect.x}, y ${e.rect.y}, ${e.rect.width}×${e.rect.height}`;
  const parts: string[] = [];
  if (!isImage) {
    parts.push(`font ${e.fontFamily ? `${e.fontFamily} ` : ''}${e.fontSizePx}px/${e.lineHeight} ${e.fontWeight}, letter-spacing ${e.letterSpacing}`);
    parts.push(`color ${e.runs.length > 0 ? 'see runs' : hexRef(e.color)}`);
  }
  parts.push(`background ${hexRef(e.background)}`);
  parts.push(`border ${e.border ?? 'none'}`);
  parts.push(`radius ${radiusText(e.radius, e.pill)}`);
  parts.push(`padding ${e.padding ?? 'none'}`);
  const lines = [`${head} — ${parts.join('; ')}`];
  if (e.src) lines.push(`  - source: ${code(shortUrl(e.src, 80))}`);
  if (e.tailwind) lines.push(`  - classes: ${code(clip(e.tailwind, caps.classChars))}`);
  e.runs.forEach((run, i) => {
    const color = run.gradientText ? 'gradient-painted text' : `color ${hexRef(run.color ? { hex: run.color, token: run.colorToken } : null)}`;
    lines.push(`  - run ${i + 1}: “${clip(run.text, 70)}” ${color}, weight ${run.fontWeight}${run.fontSizePx ? `, ${run.fontSizePx}px` : ''}`);
  });
  for (const note of e.notes) if (!hideNotes.has(note)) lines.push(`  - note: ${note}`);
  return lines;
}

function keyElementsBlock(s: PageSection, caps: Caps): string[] {
  const limit = s.index < KEY_ELEMENTS.protectedSections ? KEY_ELEMENTS.maxPerSection : Math.min(KEY_ELEMENTS.maxPerSection, caps.keyElements);
  const shown = s.keyElements.slice(0, limit);
  if (shown.length === 0) return [];
  // A note that applies to every element (a hero gradient behind all of the text) is stated once.
  const counts = new Map<string, number>();
  for (const e of shown) for (const n of new Set(e.notes)) counts.set(n, (counts.get(n) ?? 0) + 1);
  const shared = shown.length >= 3 ? [...counts].filter(([, n]) => n === shown.length).map(([note]) => note) : [];
  const lines = ['- **Key elements** (reading order; measured values, use exactly):'];
  if (shared.length > 0) lines.push(`  - applies to all of them: ${shared.join('; ')}`);
  for (const e of shown) lines.push(...keyElementLines(e, caps, new Set(shared)).map((l) => `  ${l}`));
  if (s.keyElements.length > shown.length) lines.push(`  - … ${s.keyElements.length - shown.length} more key elements in this section (capture.json)`);
  return lines;
}

function geometryLines(s: PageSection): string[] {
  const g = s.geometry;
  const ink = g.inkLeft !== null && g.inkRight !== null ? `; visible content spans x ${g.inkLeft}–${g.inkRight} (${g.inkRight - g.inkLeft}px)` : '';
  const lines = [`- **Container:** content box starts at x ${g.contentLeft}, ${g.contentWidth}px wide, max-width ${g.maxWidth ? px(g.maxWidth) : 'none'}${ink}`];
  const decorative = describeLines(g.lines);
  if (decorative.length > 0) lines.push(`- **Decorative lines** (border-only or hairline elements, not content): ${decorative.join('; ')}`);
  return lines;
}

function layoutSection(input: DesignMdInput, caps: Caps): string[] {
  const { sections } = input.layout;
  const lines = ['## 4. Layout', '', `${sections.length} section${sections.length === 1 ? '' : 's'}, top to bottom. Build them in this order.`, ''];
  if (sections.length === 0) lines.push('No sections were detected; use the full-page screenshot.', '');
  for (const s of sections.slice(0, caps.sections)) {
    const shot = input.screens.sections.find((x) => x.name === s.name);
    lines.push(
      `### ${s.index + 1}. ${s.name} (${code(`<${s.tag}>`)}, y ${Math.round(s.rect.y)}–${Math.round(s.rect.y + s.rect.height)}, ${Math.round(s.rect.width)}×${Math.round(s.rect.height)})`,
      '',
      `- **Background:** ${s.background.token ? `${code(`bg-${s.background.token}`)} ` : ''}${s.background.hex ? code(s.background.hex) : 'none'}${s.background.gradient ? `, gradient ${code(clip(s.background.gradient, 160))}` : ''}`,
      `- **Layout:** ${describeLayout(s)}`,
    );
    if (s.headings.length > 0) lines.push(`- **Headings:** ${s.headings.map((h) => `“${h}”`).join(', ')}`);
    lines.push(...geometryLines(s));
    if (s.tailwind) lines.push(`- **Classes:** ${code(clip(s.tailwind, caps.classChars))}`);
    lines.push(...keyElementsBlock(s, caps));
    lines.push(`- **Screenshot:** ${shot ? code(shot.path) : 'not available'}`, '');
  }
  lines.push(...more(Math.min(caps.sections, sections.length), sections.length, 'sections'));
  if (input.screens.fullPage) lines.push('', `Full page: ${code(input.screens.fullPage.path)}`, '');
  return lines;
}

function componentBlock(c: ComponentGroup, caps: Caps): string[] {
  const lines = [
    `### ${c.name} — ${c.count}× ${c.kind}`,
    '',
    `- **Element:** ${code(`<${c.tag}>`)}, about ${c.size.width}×${c.size.height}px${c.section ? `, mostly in “${c.section}”` : ''}${c.text ? `, e.g. “${c.text}”` : ''}`,
    `- **Structure:** ${code(c.structure)}`,
    `- **Classes:** ${c.tailwind ? code(clip(c.tailwind, caps.classChars)) : '(browser defaults)'}`,
    `- **Border radius:** ${radiusText(c.radius, c.pill)}`,
  ];
  for (const v of c.variants.slice(0, caps.variants)) {
    const diff = Object.entries(v.diff).map(([k, val]) => `${k}: ${val}`).join('; ');
    lines.push(`- **Variant (${v.count}×):** ${v.tailwind ? code(clip(v.tailwind, caps.classChars)) : 'differs only in unmapped properties'} — ${clip(diff, 200)}`);
  }
  for (const s of c.states.slice(0, caps.states)) {
    const note = s.onDescendant ? ' (styles a child; put `group` on the component)' : '';
    lines.push(`- **${s.state}${note}:** ${s.tailwind ? code(clip(s.tailwind, caps.classChars)) : clip(Object.entries(s.declarations).map(([k, v]) => `${k}: ${v}`).join('; '), 200)}`);
  }
  lines.push('');
  return lines;
}

function componentSection(input: DesignMdInput, caps: Caps): string[] {
  const { components } = input.layout;
  const lines = ['## 5. Components', '', 'Structures that repeat on the page, most important first. Names come from tags, roles and looks (never from class names).', ''];
  if (components.length === 0) lines.push('No repeated components were detected.', '');
  for (const c of components.slice(0, caps.components)) lines.push(...componentBlock(c, caps));
  lines.push(...more(Math.min(caps.components, components.length), components.length, 'components'));
  return lines;
}

function assetsSection(input: DesignMdInput, caps: Caps): string[] {
  const { assets } = input;
  const lines = ['## 6. Assets index', ''];
  const logo = assets.logo;
  const logoImage = logo?.kind === 'img' ? assets.images.find((i) => i.id === logo.assetId) : undefined;
  const logoIcon = logo?.kind === 'svg' ? assets.icons.find((i) => i.id === logo.assetId) : undefined;
  lines.push(
    `**Logo:** ${logo ? `${logoImage?.path ? code(logoImage.path) : logoIcon?.path ? code(logoIcon.path) : (logoImage ? shortUrl(logoImage.url) : 'inline SVG')} in “${logo.section ?? 'header'}” — replace with a placeholder unless the user owns it` : 'not detected'}`,
    '',
    '### Images',
    '',
    ...table(
      ['File', 'Source', 'Shown', 'Natural', 'Section', 'Alt'],
      assets.images.slice(0, caps.images).map((i) => [
        i.path ? code(i.path) : `(not saved: ${i.skipped ?? 'not downloaded'})`,
        i.kind === 'css-background' ? `background: ${shortUrl(i.url, 60)}` : shortUrl(i.url, 60),
        `${i.displayWidth}×${i.displayHeight}`,
        i.naturalWidth ? `${i.naturalWidth}×${i.naturalHeight}` : '',
        i.section,
        i.alt ? clip(i.alt, 40) : '',
      ]),
    ),
    ...more(Math.min(caps.images, assets.images.length), assets.images.length, 'images'),
  );
  if (assets.images.length === 0) lines.push('None.');
  lines.push('', '### Icons (inline SVG)', '');
  if (assets.icons.length === 0) lines.push('None.');
  for (const i of assets.icons.slice(0, caps.icons)) {
    lines.push(`- ${i.path ? code(i.path) : i.id}: ${i.width}×${i.height}, used ${i.count}×${i.label ? `, “${clip(i.label, 40)}”` : ''}${i.sections.length ? `, in ${i.sections.slice(0, 3).join(', ')}` : ''}`);
  }
  lines.push(...more(Math.min(caps.icons, assets.icons.length), assets.icons.length, 'icons'));
  lines.push('', '### Favicons', '');
  if (assets.favicons.length === 0) lines.push('None declared.');
  for (const f of assets.favicons) lines.push(`- ${f.path ? code(f.path) : shortUrl(f.url)} (${f.rel}${f.sizes ? `, ${f.sizes}` : ''})`);
  lines.push('', '### Fonts', '');
  if (assets.fonts.length === 0) lines.push('No @font-face rules (system or hosted fonts such as Google Fonts that load from a stylesheet are not listed).');
  for (const f of assets.fonts.slice(0, caps.fonts)) {
    lines.push(`- **${f.family}** — weights ${f.weights.join(', ')}; styles ${f.styles.join(', ')}${f.display ? `; display ${f.display}` : ''}; ${f.sources.slice(0, 2).map((s) => shortUrl(s.url, 70)).join(' | ')}`);
  }
  lines.push(...more(Math.min(caps.fonts, assets.fonts.length), assets.fonts.length, 'font families'), '');
  return lines;
}

function responsiveSection(input: DesignMdInput, caps: Caps): string[] {
  const { tokens, css } = input;
  const lines = ['## 7. Responsive breakpoints and dark mode', '', '### Breakpoints', ''];
  if (tokens.breakpoints.length === 0) lines.push('No media-query breakpoints found.');
  else lines.push(`Min-width breakpoints used by the page: ${tokens.breakpoints.map((b) => `${b.px}px (${b.count} rules)`).join(', ')}. Match them with Tailwind's \`sm\`/\`md\`/\`lg\`/\`xl\` (customized in theme.css).`);
  const mobile = css.breakpoints.filter((b) => b.feature === 'max-width' && b.px !== null).slice(0, 4);
  if (mobile.length > 0) lines.push(`Max-width queries: ${mobile.map((b) => `${b.value} (${b.count})`).join(', ')}.`);
  lines.push('', '### Dark mode', '');
  const d = css.darkMode;
  if (!d.detected) lines.push('No dark theme detected.');
  else {
    lines.push(`Detected${d.viaMediaQuery ? ' via `prefers-color-scheme`' : ''}${d.selectors.length ? `; selectors: ${d.selectors.slice(0, 5).map(code).join(', ')}` : ''}; ${d.ruleCount} rules, ${d.variables.length} overridden variables.`);
    for (const v of d.variables.slice(0, caps.variables)) lines.push(`- ${code(v.name)}: ${code(clip(v.value, 60))}`);
    lines.push(...more(Math.min(caps.variables, d.variables.length), d.variables.length, 'variables'));
  }
  return [...lines, ''];
}

function motionSection(input: DesignMdInput, caps: Caps): string[] {
  const { motion } = input.tokens;
  const lines = ['## 8. Motion', ''];
  lines.push(`- **Transition durations:** ${motion.durations.map((d) => `${d.ms}ms (${d.count})`).join(', ') || 'none'}`);
  lines.push(`- **Easings:** ${motion.easings.map((e) => `${code(clip(e.value, 60))} (${e.count})`).join(', ') || 'none'}`);
  lines.push('', '### Keyframes', '');
  if (input.css.keyframes.length === 0) lines.push('None.');
  for (const k of input.css.keyframes.slice(0, caps.keyframes)) lines.push(`- ${code(k.name)}: ${k.steps} steps, animates ${k.properties.join(', ') || 'n/a'}`);
  lines.push(...more(Math.min(caps.keyframes, input.css.keyframes.length), input.css.keyframes.length, 'keyframes'), '');
  return lines;
}

function render(input: DesignMdInput, caps: Caps): string {
  const title = input.capture.meta.title || input.capture.meta.url;
  return [
    `# Design pack: ${title}`,
    '',
    ...instructions(),
    ...overview(input, caps),
    ...tokenSection(input, caps),
    ...layoutSection(input, caps),
    ...componentSection(input, caps),
    ...assetsSection(input, caps),
    ...responsiveSection(input, caps),
    ...motionSection(input, caps),
  ]
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd() + '\n';
}

/**
 * The rule-based design.md. Sections 1–8 in a fixed order. If the result is over `maxChars` the
 * generator re-renders with shorter lists (summarizing rather than listing everything) and, as a
 * last resort, cuts at a line break with a note.
 */
export function generateDesignMd(input: DesignMdInput): string {
  const max = input.maxChars ?? OUTPUT_LIMITS.maxDesignMdChars;
  let out = '';
  for (const caps of LEVELS) {
    out = render(input, caps);
    if (out.length <= max) return out;
  }
  const note = '\n\n_design.md was cut to fit the size limit; see tokens.json and capture.json for the full data._\n';
  const cut = out.slice(0, Math.max(0, max - note.length));
  return cut.slice(0, Math.max(cut.lastIndexOf('\n'), 0)) + note;
}
